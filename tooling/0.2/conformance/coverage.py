#!/usr/bin/env python3
"""Generate or check the 0.2.0 corpus rule-code coverage table from cases.py."""
import re
import sys
from pathlib import Path

from cases import ROOT, cases

TARGET = Path(__file__).with_name('COVERAGE.md')
SPEC = ROOT.parents[1] / 'spec' / '0.2' / 'validation.md'
MINIMUM = 2


def static_codes():
    text = SPEC.read_text(encoding='utf-8')
    section = text.split('## Static checks and evidence limits', 1)[1].split('\n## ', 1)[0]
    return re.findall(r'^\| `([A-Z_]+)` \|', section, re.MULTILINE)


def render():
    corpus = cases()
    witnesses = {code: [] for code in static_codes()}
    accepted = []
    for case in corpus:
        if not case['codes']:
            accepted.append(case['name'])
        for code in case['codes']:
            witnesses.setdefault(code, []).append(case['name'])
    lines = [
        '# 0.2.0 corpus rule-code coverage',
        '',
        'Generated by `python3 tooling/0.2/conformance/coverage.py` from [cases.py](cases.py).',
        'Do not edit by hand. The static rule codes come from the',
        '[validation chapter](../../../spec/0.2/validation.md#static-checks-and-evidence-limits).',
        'A failing witness is a case whose expected code set contains the code.',
        'Counts describe this corpus only; they are not exhaustive rule-combination coverage.',
        '',
        f'Cases: {len(corpus)}. Accepted cases: {len(accepted)}. Minimum failing witnesses per code: {MINIMUM}.',
        '',
        '| Code | Failing witnesses | Cases |',
        '| --- | ---: | --- |',
    ]
    for code, names in witnesses.items():
        lines.append(f'| `{code}` | {len(names)} | ' + ', '.join(f'`{n}`' for n in sorted(names)) + ' |')
    return '\n'.join(lines) + '\n', witnesses


def main():
    text, witnesses = render()
    weak = [code for code, names in witnesses.items() if len(names) < MINIMUM]
    if sys.argv[1:] == ['--check']:
        if weak:
            print('Codes below the minimum: ' + ', '.join(weak), file=sys.stderr)
            return 1
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8') != text:
            print('COVERAGE.md is stale; run python3 tooling/0.2/conformance/coverage.py', file=sys.stderr)
            return 1
        print(f'0.2.0 corpus coverage is current: {len(witnesses)} codes.')
        return 0
    if sys.argv[1:]:
        print('Usage: coverage.py [--check]', file=sys.stderr)
        return 2
    TARGET.write_text(text, encoding='utf-8')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
